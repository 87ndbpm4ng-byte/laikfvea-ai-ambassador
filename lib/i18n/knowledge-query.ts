export function createKnowledgeQueryText(
  message: string,
  language?: string | null,
) {
  const resolvedLanguage = resolveSupportedLanguage(language);
  if (resolvedLanguage === "en") return message.trim();

  const terms = resolvedLanguage === "ru"
    ? RUSSIAN_QUERY_TERMS
    : resolvedLanguage === "fr"
      ? FRENCH_QUERY_TERMS
    : resolvedLanguage === "yue"
      ? CANTONESE_QUERY_TERMS
      : CHINESE_QUERY_TERMS;

  return terms.reduce(
    (translated, [pattern, replacement]) =>
      translated.replace(pattern, replacement),
    message,
  )
    .replace(/[^\p{Script=Latin}\p{Number}\s-]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}
